// Code generator for the RAIL0 Rust SDK.
//
// Reads the OpenAPI schema (in priority order):
//   1. RAIL0_SCHEMA_PATH env var — absolute path to a local openapi.json
//   2. Default: ../rail0-api/docs/openapi.json (sibling repo on the local filesystem)
//
// Emits:
//   src/types_gen.rs  — Serde-derived structs for every schema in the spec
//   src/accounts.rs   — AccountsClient with payment_methods, wallets, wallet
//   src/payments.rs   — PaymentsClient with all payment lifecycle operations
//   src/chains.rs     — ChainsClient with list
//   src/tokens.rs     — TokensClient with list
//
// Run:
//
//   cargo run --bin generate

use std::collections::BTreeMap;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::path::PathBuf;

use serde::Deserialize;
use serde_json::Value;

#[derive(Debug, Deserialize)]
struct OpenApi {
    components: Components,
}

#[derive(Debug, Deserialize)]
struct Components {
    schemas: BTreeMap<String, Value>,
}

fn main() {
    // Resolve paths relative to the workspace root (where Cargo.toml lives).
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let spec_path = if let Ok(p) = std::env::var("RAIL0_SCHEMA_PATH") {
        PathBuf::from(p)
    } else {
        manifest_dir.join("..").join("rail0-api").join("docs").join("openapi.json")
    };
    let src_dir = manifest_dir.join("src");

    let spec_bytes = fs::read(&spec_path)
        .unwrap_or_else(|e| panic!("Cannot read {}: {e}", spec_path.display()));

    let api: OpenApi = serde_json::from_slice(&spec_bytes)
        .unwrap_or_else(|e| panic!("Cannot parse openapi.json: {e}"));

    // ── types_gen.rs ──────────────────────────────────────────────────────────
    let types_path = src_dir.join("types_gen.rs");
    let types_src = generate_types(&api.components.schemas);
    fs::write(&types_path, &types_src)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", types_path.display()));
    println!("Generated {}", types_path.display());

    // ── chains.rs ─────────────────────────────────────────────────────────────
    let chains_path = src_dir.join("chains.rs");
    fs::write(&chains_path, CHAINS_SRC)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", chains_path.display()));
    println!("Generated {}", chains_path.display());

    // ── tokens.rs ─────────────────────────────────────────────────────────────
    let tokens_path = src_dir.join("tokens.rs");
    fs::write(&tokens_path, TOKENS_SRC)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", tokens_path.display()));
    println!("Generated {}", tokens_path.display());

    // ── accounts.rs ───────────────────────────────────────────────────────────
    let accounts_path = src_dir.join("accounts.rs");
    fs::write(&accounts_path, ACCOUNTS_SRC)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", accounts_path.display()));
    println!("Generated {}", accounts_path.display());

    // ── payments.rs ───────────────────────────────────────────────────────────
    let payments_path = src_dir.join("payments.rs");
    fs::write(&payments_path, PAYMENTS_SRC)
        .unwrap_or_else(|e| panic!("Cannot write {}: {e}", payments_path.display()));
    println!("Generated {}", payments_path.display());

    println!("Done.");
}

// ── types_gen.rs generation ───────────────────────────────────────────────────

fn generate_types(schemas: &BTreeMap<String, Value>) -> String {
    let mut out = String::from(
        "// Code generated by gen/generate.rs — DO NOT EDIT.\n\
         // Re-run `cargo run --bin generate` after updating rail0-api/docs/openapi.json.\n\n\
         #![allow(dead_code)]\n\n\
         use serde::{Deserialize, Serialize};\n\n",
    );

    for (name, schema) in schemas {
        if let Some(struct_src) = schema_to_struct(name, schema) {
            out.push_str(&struct_src);
            out.push('\n');
        }
    }

    // Hardcoded extra types for pagination and new resource types
    out.push_str(EXTRA_TYPES);

    out
}

/// Schema names that are hardcoded in EXTRA_TYPES and must not be generated from the spec.
const HARDCODED_TYPES: &[&str] = &["WalletToken", "PaymentSummary", "TransactionRecord"];

fn schema_to_struct(name: &str, schema: &Value) -> Option<String> {
    // Skip types we hardcode manually (they may or may not be in the spec)
    if HARDCODED_TYPES.contains(&name) {
        return None;
    }

    let ty = schema.get("type").and_then(Value::as_str).unwrap_or("");
    if ty != "object" {
        return None; // skip primitives (Address, Bytes32, etc.) — handled in types.rs
    }

    let properties = schema.get("properties")?.as_object()?;
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|arr| arr.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();

    let mut src = String::new();

    if let Some(desc) = schema.get("description").and_then(Value::as_str) {
        writeln!(src, "/// {}", desc.replace('\n', "\n/// ")).ok();
    }

    writeln!(src, "#[derive(Debug, Clone, Serialize, Deserialize)]").ok();
    writeln!(src, "pub struct {} {{", name).ok();

    for (field, prop) in properties {
        let rust_field = to_snake_case(field);
        let is_required = required.contains(&field.as_str());
        let rust_type = openapi_type_to_rust(prop, is_required);

        // Add serde rename if the field name differs from the JSON key
        if rust_field != *field {
            writeln!(src, "    #[serde(rename = \"{field}\")]").ok();
        }
        // Add skip_serializing_if for Option fields
        if !is_required {
            writeln!(src, "    #[serde(skip_serializing_if = \"Option::is_none\")]").ok();
        }
        if let Some(desc) = prop.get("description").and_then(Value::as_str) {
            writeln!(src, "    /// {desc}").ok();
        }
        writeln!(src, "    pub {rust_field}: {rust_type},").ok();
    }

    writeln!(src, "}}").ok();
    Some(src)
}

fn openapi_type_to_rust(prop: &Value, required: bool) -> String {
    let rust = if prop.get("$ref").is_some() || prop.get("allOf").is_some() {
        "String".to_string() // all refs are string primitives in this spec
    } else {
        match prop.get("type").and_then(Value::as_str).unwrap_or("") {
            "string" => "String".to_string(),
            "boolean" => "bool".to_string(),
            "integer" => {
                if prop.get("format").and_then(Value::as_str) == Some("int64") {
                    "i64".to_string()
                } else {
                    "u32".to_string()
                }
            }
            "object" => "serde_json::Value".to_string(),
            _ => "serde_json::Value".to_string(),
        }
    };

    if required { rust } else { format!("Option<{rust}>") }
}

fn to_snake_case(s: &str) -> String {
    // Already snake_case or camelCase → convert camelCase to snake_case
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(ch.to_lowercase().next().unwrap());
    }
    out
}

